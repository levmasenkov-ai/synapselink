function checkTypedAnswer() {
    const inputField = document.getElementById('user-answer');
    const userAnswer = inputField.value.trim();
    if (userAnswer === "") return;
    
    const q = currentQuestions[currentQuestionIndex];
    
    if (userAnswer === q.correct) {
        clearInterval(timerInterval); 
        correctAnswersCount++;
        currentQuestionIndex++; // Переходим к следующему вопросу ТОЛЬКО при правильном ответе
        totalTasksCompleted++;  // Засчитываем решенную задачу в общую статистику

        // ПРОВЕРКА: Закончились ли вопросы в уровне?
        if (currentQuestionIndex >= currentQuestions.length) {
            if (correctAnswersCount >= 3) { 
                if (currentLevel === currentUnlockedLevel) {
                    currentUnlockedLevel++;
                    localStorage.setItem('math_game_level', currentUnlockedLevel);
                }
            }
            openAdvisor(); // Уровень пройден, открываем экран разбора
        } else {
            // Перед показом следующего вопроса обнуляем счетчик ошибок и прячем прошлую подсказку
            failedAttemptsCount = 0;
            document.getElementById('hint-action-btn').style.display = 'none';
            showQuestion(); 
        }
    } else {
        // При неверном ответе индекс НЕ увеличиваем! Оставляем игрока на этой же задаче
        clearInterval(timerInterval);
        handleWrongAnswer();
    }
}


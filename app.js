/* === ВСТАВЬТЕ ЭТОТ КУСОК КОДА В САМЫЙ КОНЕЦ ФАЙЛА app.js === */
function sendGameRating(starsCount, containerRow) {
    // 1. ПОДСВЕЧИВАЕМ ПЕШКИ В ИНТЕРФЕЙСЕ
    const pawns = containerRow.querySelectorAll('.pawn-pwa');
    pawns.forEach((p, idx) => {
        if (idx < starsCount) {
            p.classList.add('active'); 
        } else {
            p.classList.remove('active'); 
        }
    });

    // 2. СОХРАНЯЕМ В ЛОКАЛЬНУЮ ПАМЯТЬ БРАУЗЕРА
    localStorage.setItem('game_rating_value', starsCount);

    // 3. ССЫЛКА НА ВАШУ GOOGLE ТАБЛИЦУ
    // Вставьте скопированную ссылку из Google Apps Script вместо текста ниже:
    const googleScriptUrl = "https://script.google.com/macros/s/AKfycbzx0BRmW9B2F4zv8B-_IAohdlHfASDNe9uBNM0K-AV1ZlXFAny4mz_DDhuyAxVPL2-xoA/exec";

    // Проверяем, вставили ли вы ссылку
    if (googleScriptUrl !== "СЮДА_ВСТАВЬТЕ_СЫЛКУ_ИЗ_GOOGLE") {
        // Отправляем данные в таблицу
        fetch(googleScriptUrl, {
            method: 'POST',
            mode: 'no-cors', // Важно для обхода строгой политики Google
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({ rating: starsCount })
        })
        .then(() => console.log('Данные успешно отправлены в Google Таблицу!'))
        .catch(err => console.error('Ошибка отправки в таблицу:', err));
    }
}



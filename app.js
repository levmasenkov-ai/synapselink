function navigateTo(screenId) {
    document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
    document.getElementById(screenId).classList.add('active');

    // Получаем доступ к плеерам
    const menuMusic = document.getElementById('bgm-menu');
    const gameMusic = document.getElementById('bgm-game');
    const gameoverMusic = document.getElementById('bgm-gameover');

    // Функция для безопасного запуска музыки с обходом блокировок
    const playMusic = (track) => {
        track.volume = 0.25; // Комфортная громкость 25%
        track.play().catch(err => {
            console.log("Браузер заблокировал автозвук. Ожидаем клика пользователя...");
            
            // Единоразовый «будильник»: как только пользователь кликнет в любом месте, музыка включится
            const startOnInteraction = () => {
                track.play().catch(e => console.log(e));
                document.removeEventListener('click', startOnInteraction);
            };
            document.addEventListener('click', startOnInteraction);
        });
    };

    // МУЗЫКАЛЬНЫЙ АВТОПЕРЕКЛЮЧАТЕЛЬ ЭКРАНОВ
    if (screenId === 'main-screen' || screenId === 'levels-screen') {
        gameMusic.pause();
        gameMusic.currentTime = 0;
        gameoverMusic.pause();
        gameoverMusic.currentTime = 0;

        if (menuMusic.paused) playMusic(menuMusic);
    } 
    else if (screenId === 'game-screen' || screenId === 'advisor-screen') {
        menuMusic.pause();
        menuMusic.currentTime = 0;
        gameoverMusic.pause();
        gameoverMusic.currentTime = 0;

        if (gameMusic.paused) playMusic(gameMusic);
    } 
    else if (screenId === 'game-over-screen') {
        menuMusic.pause();
        menuMusic.currentTime = 0;
        gameMusic.pause();
        gameMusic.currentTime = 0;

        playMusic(gameoverMusic);
    }
}

// Отрисовка экрана выбора уровней
function renderLevels() {
    const logicContainer = document.getElementById('logic-levels-container');
    const mathContainer = document.getElementById('math-levels-container');
    
    logicContainer.innerHTML = '';
    mathContainer.innerHTML = '';

    const totalLevels = 30;

    for (let i = 1; i <= totalLevels; i++) {
        const btn = document.createElement('button');
        btn.classList.add('level-btn');
        btn.innerText = `Уровень ${i}`;

        // Настройка состояний уровней (пройден/текущий/закрыт)
        if (i < currentUnlockedLevel) {
            btn.classList.add('level-passed');
            btn.onclick = () => startLevel(i);
        } else if (i === currentUnlockedLevel) {
            btn.classList.add('level-current');
            btn.onclick = () => startLevel(i);
        } else {
            btn.classList.add('level-locked');
        }

        // Распределяем уровни по контейнерам разделов
        if (i <= 19) {
            logicContainer.appendChild(btn);        // Уровни 1-11 идут в Логику
        } 
        else if (i >= 20 && i <= 29) {
            mathContainer.appendChild(btn);         // 12-34 идут в Математику
        }

    }

    //
    //    else {
    //       mathContainer.appendChild(btn);  // Остальные уровни
    //    }
    //}









    // Принудительно показываем кнопки навигации разделов, так как мы вышли в меню
    document.getElementById('main-back-btn').style.display = 'block';
    if (currentSection === 'math') {
        document.getElementById('section-back-btn').style.display = 'block';
    } else {
        document.getElementById('section-back-btn').style.display = 'none';
    }
}

